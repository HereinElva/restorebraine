#!/usr/bin/env node
/**
 * Sync ios/App/App/ghost-builds.txt from live CDN probe.
 * Format: + prefix = ALLOW (live deps, never block), plain = BLOCK (stale cache).
 */
import { execSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { buildDeviceGhostBlocklist, resolveLiveActiveAssets } from './ghost-builds-registry.mjs';

const outPath = resolve('ios/App/App/ghost-builds.txt');

function gitPublicHashes() {
  try {
    const raw = execSync(
      "git log --all -p -- 'ios/App/App/public/**' 2>/dev/null | grep -oE '(App|index)-[A-Za-z0-9_-]+\\.js' || true",
      { encoding: 'utf8', maxBuffer: 20 * 1024 * 1024 },
    );
    return [...new Set(raw.match(/(App|index)-[A-Za-z0-9_-]+\.js/g) ?? [])];
  } catch {
    return [];
  }
}

async function main() {
  const { liveIndex, liveApp, active } = await resolveLiveActiveAssets();
  const activeSet = new Set(active);

  const historicalPublic = gitPublicHashes().filter((f) => !activeSet.has(f));
  const blocklist = buildDeviceGhostBlocklist({
    active,
    ghosts: historicalPublic,
  });

  const falsePositive = blocklist.filter((f) => activeSet.has(f));
  if (falsePositive.length) {
    console.error('Refusing to sync — would block live chunks:', falsePositive.join(', '));
    process.exit(2);
  }

  mkdirSync(dirname(outPath), { recursive: true });
  const lines = [
    '# Auto-generated by npm run ghosts:sync — do not edit by hand',
    `# Live entry: ${liveIndex} → ${liveApp}`,
    '# Lines starting with + are LIVE CDN deps — never block on device',
    ...active.map((f) => `+ ${f}`),
    '# Stale WKWebView / CDN cache — block and purge',
    ...blocklist,
  ];
  writeFileSync(outPath, `${lines.join('\n')}\n`);
  console.log(`Synced ghost lists → ${outPath}`);
  console.log(`  ALLOW (live):  ${active.length} files`);
  console.log(`  BLOCK (stale): ${blocklist.length} files`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
