#!/usr/bin/env node
/** Regenerate ios/App/App/ghost-builds.txt — historical cache + CDN ghosts, never live deps. */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { buildDeviceGhostBlocklist, resolveLiveActiveAssets } from './ghost-builds-registry.mjs';

const outPath = resolve('ios/App/App/ghost-builds.txt');

async function main() {
  const { liveIndex, liveApp, active } = await resolveLiveActiveAssets();
  const blocklist = buildDeviceGhostBlocklist({ active });
  const falsePositive = blocklist.filter((f) => active.includes(f));

  if (falsePositive.length) {
    console.error('Refusing to sync — would block live dependency chunks:', falsePositive.join(', '));
    process.exit(2);
  }

  mkdirSync(dirname(outPath), { recursive: true });
  const lines = [
    '# Auto-generated by npm run ghosts:sync — do not edit by hand',
    `# Live: ${liveIndex} → ${liveApp} (${active.length} deps — never block these)`,
    ...blocklist,
  ];
  writeFileSync(outPath, `${lines.join('\n')}\n`);
  console.log(`Synced ${blocklist.length} device ghost blockers → ${outPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
