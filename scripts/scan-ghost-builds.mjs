#!/usr/bin/env node
/**
 * Scan live Base44 CDN for ghost builds — delegates to discover (full allow/block lists).
 * Usage: npm run ghosts:scan
 */
import { discoverGhostBuilds } from './discover-ghost-builds.mjs';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const report = await discoverGhostBuilds();

console.log(`
═══════════════════════════════════════════════════════════════
 GHOST BUILD SCAN — ${report.live.index} → ${report.live.app}
═══════════════════════════════════════════════════════════════
 Live deps (ALLOW):  ${report.active.length}
 Device block (stale): ${report.deviceBlocklist.length}
 CDN ghosts HTTP 200: ${report.stats.cdnGhosts}
`);

const blockPath = resolve('ios/App/App/ghost-builds.txt');
mkdirSync(dirname(blockPath), { recursive: true });
const lines = [
  '# Auto-generated by npm run ghosts:scan',
  `# Live entry: ${report.live.index} → ${report.live.app}`,
  '# Lines starting with + are LIVE CDN deps — never block on device',
  ...report.active.map((f) => `+ ${f}`),
  '# Stale WKWebView / CDN cache — block and purge',
  ...report.deviceBlocklist,
];
writeFileSync(blockPath, `${lines.join('\n')}\n`);
console.log(`Wrote ${blockPath}`);

process.exit(report.falsePositiveInBlocklist?.length ? 2 : 0);
